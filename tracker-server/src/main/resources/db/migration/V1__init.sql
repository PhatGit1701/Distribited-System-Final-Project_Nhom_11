CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    passkey VARCHAR(64) NOT NULL UNIQUE,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    is_banned BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT users_passkey_format CHECK (passkey ~ '^[0-9a-f]{64}$'),
    CONSTRAINT users_role CHECK (role IN ('USER', 'ADMIN'))
);

-- file_id is the existing API's SHA-256 identifier, not a BitTorrent v1 info_hash.
CREATE TABLE shared_files (
    file_id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    size BIGINT NOT NULL,
    chunk_size INTEGER NOT NULL,
    chunk_count INTEGER NOT NULL,
    chunk_hashes BYTEA NOT NULL,
    tracker_url TEXT NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT shared_files_hash_format CHECK (file_id ~ '^[0-9a-f]{64}$'),
    CONSTRAINT shared_files_size_positive CHECK (size > 0),
    CONSTRAINT shared_files_chunk_size CHECK (chunk_size BETWEEN 1 AND 16777216),
    CONSTRAINT shared_files_chunk_count CHECK (chunk_count BETWEEN 1 AND 100000),
    CONSTRAINT shared_files_chunk_layout CHECK (chunk_count = 1 + (size - 1) / chunk_size),
    CONSTRAINT shared_files_chunk_hash_length CHECK (octet_length(chunk_hashes) = chunk_count * 32)
);
CREATE INDEX shared_files_owner_idx ON shared_files(owner_id);
CREATE INDEX shared_files_created_idx ON shared_files(created_at);
CREATE INDEX shared_files_name_idx ON shared_files(name);

CREATE TABLE user_file_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    file_id VARCHAR(64) NOT NULL REFERENCES shared_files(file_id),
    total_uploaded BIGINT NOT NULL DEFAULT 0 CHECK (total_uploaded >= 0),
    total_downloaded BIGINT NOT NULL DEFAULT 0 CHECK (total_downloaded >= 0),
    completed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT user_file_stats_user_file_unique UNIQUE (user_id, file_id)
);
CREATE INDEX user_file_stats_file_idx ON user_file_stats(file_id);

-- Persisted reports are separate from transient heartbeat/swarm state.
CREATE TABLE peer_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    file_id VARCHAR(64) NOT NULL REFERENCES shared_files(file_id),
    peer_id VARCHAR(128) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT peer_reports_peer_nonempty CHECK (length(trim(peer_id)) > 0),
    CONSTRAINT peer_reports_reason_nonempty CHECK (length(trim(reason)) > 0)
);
CREATE INDEX peer_reports_reporter_idx ON peer_reports(reporter_id);
CREATE INDEX peer_reports_file_peer_idx ON peer_reports(file_id, peer_id);
CREATE INDEX peer_reports_created_idx ON peer_reports(created_at);
